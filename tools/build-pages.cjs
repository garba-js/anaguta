#!/usr/bin/env node
/**
 * ============================================================================
 * ANAGUTA TRADOMODERN - PAGE BUILDER (tools/build-pages.cjs)
 * ============================================================================
 * Reads js/articles-data.js and writes:
 *
 *   projects/<slug>.html   one real page per project
 *   articles/<slug>.html   one real page per article
 *   sitemap.xml            every page, for Google
 *   js/articles-pages.js   list that lets the site link to the built pages
 *   tools/slugs.json       remembers each page's address so it never changes
 *
 * WHY: WhatsApp, Facebook and Google read a page's own title and picture straight
 * from its HTML. Built pages carry each item's own title, summary, picture and full
 * text in the HTML, so a shared link shows the right preview.
 *
 * HOW TO RUN
 *   Automatic: the GitHub workflow (.github/workflows/build-pages.yml) runs this every
 *              time js/articles-data.js changes. You do nothing.
 *   By hand:   node tools/build-pages.cjs
 *
 * PAGE ADDRESSES ("slugs")
 *   Made from the title the first time an item is built, then locked in tools/slugs.json,
 *   so fixing a typo in a title never breaks a link you already shared.
 *   To choose your own, add   slug: "my-address",   to the item in articles-data.js.
 *
 * Nothing to install: this uses only what comes with Node.
 * ============================================================================
 */
'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');

/* ------------------------------ SETTINGS ------------------------------ */
// No trailing slash. Change this (and SITE_BASE in js/articles.js) if the site moves to its own domain.
const SITE_URL = 'https://garba-js.github.io/anaguta';

const DEFAULT_SHARE_IMAGE = 'images/og-image.jpg';
const PUBLISHER_NAME = 'Anaguta Tradomodern';
const PUBLISHER_LOGO = 'images/logo.png';
const STATIC_PAGES = ['', 'about_us.html', 'history.html', 'dictionary.html', 'gallery.html', 'event.html', 'contact.html', 'articles.html'];
const FOLDERS = { project: 'projects', article: 'articles' };
const MARKER = 'GENERATED by tools/build-pages';
/* ---------------------------------------------------------------------- */

const rootArg = process.argv.find((a) => a.startsWith('--root='));
const ROOT = rootArg ? path.resolve(rootArg.slice(7)) : path.resolve(__dirname, '..');
const TEMPLATE = path.join(__dirname, 'article-template.html');
const SLUGS_FILE = path.join(ROOT, 'tools', 'slugs.json');

const stats = { created: 0, updated: 0, unchanged: 0, removed: 0 };
const warnings = [];

/* ------------------------------- helpers ------------------------------- */
const esc = (s) =>
  String(s == null ? '' : s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

function writeIfChanged(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (fs.existsSync(file)) {
    if (fs.readFileSync(file, 'utf8') === content) {
      stats.unchanged++;
      return;
    }
    stats.updated++;
  } else {
    stats.created++;
  }
  fs.writeFileSync(file, content, 'utf8');
}

function slugify(text) {
  return String(text)
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

// Keep addresses readable: cut at a whole word, around 60 characters
function shorten(slug, max) {
  if (slug.length <= max) return slug;
  const cut = slug.slice(0, max);
  const i = cut.lastIndexOf('-');
  return i > 20 ? cut.slice(0, i) : cut;
}

// "October 24, 2026" or "2026" -> "2026-10-24" (uses local date parts so the day never shifts)
function isoDate(text) {
  const t = Date.parse(text);
  if (isNaN(t)) return null;
  const d = new Date(t);
  const p = (n) => String(n).padStart(2, '0');
  return d.getFullYear() + '-' + p(d.getMonth() + 1) + '-' + p(d.getDate());
}

function absolute(p) {
  if (/^https?:\/\//i.test(p)) return p;
  return SITE_URL + '/' + encodeURI(String(p).replace(/^\.?\//, ''));
}

/* ----------------------------- load the data ----------------------------- */
function loadItems() {
  const file = path.join(ROOT, 'js', 'articles-data.js');
  if (!fs.existsSync(file)) throw new Error('Cannot find ' + file);
  const code = fs.readFileSync(file, 'utf8');
  const items = vm.runInNewContext(code + '\n;AnagutaArticles', { window: {} });
  if (!Array.isArray(items)) throw new Error('js/articles-data.js did not produce a list');

  const seen = new Set();
  const good = [];
  items.forEach((a, i) => {
    if (a == null || a.id == null || !a.title) {
      warnings.push('Entry #' + (i + 1) + ' in articles-data.js has no id or no title, so it was skipped.');
      return;
    }
    if (seen.has(String(a.id))) throw new Error('Two entries share id ' + a.id + '. Every id must be unique.');
    seen.add(String(a.id));
    good.push(a);
  });
  return good;
}

/* ------------------------------- slugs ------------------------------- */
function assignSlugs(items) {
  let stored = {};
  if (fs.existsSync(SLUGS_FILE)) stored = JSON.parse(fs.readFileSync(SLUGS_FILE, 'utf8'));

  const result = {};
  const used = new Set();
  const take = (slug) => {
    let s = slug || 'item';
    let n = 2;
    while (used.has(s)) s = slug + '-' + n++;
    used.add(s);
    return s;
  };

  // Explicit and already-locked slugs claim their addresses first
  items.forEach((a) => {
    const explicit = a.slug ? slugify(a.slug) : '';
    const locked = stored[String(a.id)];
    const wanted = explicit || locked;
    if (wanted) result[a.id] = take(wanted);
  });
  // New items get an address made from the title
  items.forEach((a) => {
    if (!result[a.id]) result[a.id] = take(shorten(slugify(a.title), 60));
  });

  const merged = Object.assign({}, stored);
  items.forEach((a) => (merged[String(a.id)] = result[a.id]));
  const ordered = {};
  Object.keys(merged)
    .sort((x, y) => Number(x) - Number(y))
    .forEach((k) => (ordered[k] = merged[k]));
  writeIfChanged(SLUGS_FILE, JSON.stringify(ordered, null, 2) + '\n');
  return result;
}

/* ------------------------------ page content ------------------------------ */
const KINDS = {
  project: { kind: 'Project', backText: 'Back to All Projects', related: 'Related <em>Projects</em>' },
  article: { kind: 'Article', backText: 'Back to All Essays', related: 'Related <em>Essays</em>' }
};

function jsonLd(a, type, url, ogImage, iso) {
  const orgLike = /\b(team|lab|media|collective|initiative|cell|council|documentation|research|committee)\b|&/i.test(a.author || '');
  const author = a.author
    ? { '@type': orgLike ? 'Organization' : 'Person', name: a.author }
    : { '@type': 'Organization', name: PUBLISHER_NAME };

  const article = {
    '@context': 'https://schema.org',
    '@type': 'Article',
    headline: a.title,
    description: a.excerpt || '',
    image: [ogImage],
    author,
    publisher: { '@type': 'Organization', name: PUBLISHER_NAME, logo: { '@type': 'ImageObject', url: absolute(PUBLISHER_LOGO) } },
    mainEntityOfPage: { '@type': 'WebPage', '@id': url },
    inLanguage: 'en'
  };
  if (iso) {
    article.datePublished = iso;
    article.dateModified = iso;
  }
  if (a.category) article.articleSection = a.category;
  if (a.tags && a.tags.length) article.keywords = a.tags.join(', ');

  const crumbs = {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Home', item: SITE_URL + '/' },
      { '@type': 'ListItem', position: 2, name: type === 'project' ? 'Projects' : 'Articles', item: SITE_URL + '/articles.html?type=' + type },
      { '@type': 'ListItem', position: 3, name: a.title, item: url }
    ]
  };
  // "<" is escaped so the data can never end the script tag early
  return JSON.stringify([article, crumbs]).replace(/</g, '\\u003c');
}

function renderPage(template, a, type, slug) {
  const folder = FOLDERS[type];
  const kind = KINDS[type];
  const url = SITE_URL + '/' + folder + '/' + slug + '.html';
  const shareImage = a.ogImage || a.image || DEFAULT_SHARE_IMAGE;
  const ogImage = absolute(shareImage);
  const iso = isoDate(a.date);

  const articleMeta = [];
  if (iso) articleMeta.push('  <meta property="article:published_time" content="' + iso + '">');
  if (a.category) articleMeta.push('  <meta property="article:section" content="' + esc(a.category) + '">');
  (a.tags || []).forEach((t) => articleMeta.push('  <meta property="article:tag" content="' + esc(t) + '">'));

  const values = {
    TITLE: esc(a.title),
    DESCRIPTION: esc(a.excerpt || ''),
    AUTHOR: esc(a.author || 'Tradomodern Research Team'),
    URL: esc(url),
    OG_IMAGE: esc(ogImage),
    ARTICLE_META: articleMeta.join('\n'),
    JSONLD: jsonLd(a, type, url, ogImage, iso),
    ID: esc(a.id),
    TYPE: type,
    KIND: kind.kind,
    CATEGORY: esc(a.category || ''),
    READTIME: esc(a.readTime || '5 min read'),
    DATE: esc(a.date || ''),
    IMAGE_SRC: esc(encodeURI(a.image || DEFAULT_SHARE_IMAGE)),
    CONTENT: (a.content || '').trim(),
    BACK_HREF: 'articles.html?type=' + type,
    BACK_TEXT: kind.backText,
    RELATED_TITLE: kind.related
  };

  // Single pass, so text inside an article that happens to look like {{SOMETHING}} is left alone
  return template.replace(/\{\{([A-Z_]+)\}\}/g, (m, key) => (key in values ? values[key] : m));
}

/* ---------------------------------- main ---------------------------------- */
function main() {
  const items = loadItems();
  const template = fs.readFileSync(TEMPLATE, 'utf8');
  const slugs = assignSlugs(items);

  const built = {}; // id -> "projects/slug.html"
  const webpShare = [];
  const keep = new Set();

  items.forEach((a) => {
    const type = a.type === 'project' ? 'project' : 'article';
    const rel = FOLDERS[type] + '/' + slugs[a.id] + '.html';
    built[a.id] = rel;
    keep.add(rel);
    writeIfChanged(path.join(ROOT, rel), renderPage(template, a, type, slugs[a.id]));

    // friendly warnings
    const img = a.image;
    if (img && !/^https?:/i.test(img) && !fs.existsSync(path.join(ROOT, img))) {
      warnings.push('"' + a.title + '": the picture ' + img + ' was not found in the site folder.');
    }
    const share = a.ogImage || a.image || DEFAULT_SHARE_IMAGE;
    if (/\.webp$/i.test(share)) webpShare.push(a.title);
  });

  if (webpShare.length) {
    warnings.push(
      webpShare.length + ' item(s) use a WebP picture for link previews, and WhatsApp does not always show those: ' +
        webpShare.slice(0, 3).map((t) => '"' + t + '"').join(', ') + (webpShare.length > 3 ? ', ...' : '') +
        '. For a reliable preview add  ogImage: "images/name.jpg"  to the item (JPEG, about 1200x630, under 300 KB).'
    );
  }

  // Remove pages for items that no longer exist (only files this tool made; hand-made files are never touched)
  Object.values(FOLDERS).forEach((folder) => {
    const dir = path.join(ROOT, folder);
    if (!fs.existsSync(dir)) return;
    fs.readdirSync(dir)
      .filter((f) => f.endsWith('.html'))
      .forEach((f) => {
        const rel = folder + '/' + f;
        if (keep.has(rel)) return;
        const full = path.join(dir, f);
        if (fs.readFileSync(full, 'utf8').includes(MARKER)) {
          fs.unlinkSync(full);
          stats.removed++;
        }
      });
  });

  // js/articles-pages.js
  const ordered = {};
  Object.keys(built)
    .sort((x, y) => Number(x) - Number(y))
    .forEach((k) => (ordered[k] = built[k]));
  writeIfChanged(
    path.join(ROOT, 'js', 'articles-pages.js'),
    '/* AUTO-GENERATED by tools/build-pages.cjs - do not edit by hand.\n' +
      '   Maps each item\'s id to its own page, so the site can link to it. */\n' +
      'window.AnagutaPages = ' + JSON.stringify(ordered, null, 2) + ';\n'
  );

  // sitemap.xml
  const urls = STATIC_PAGES.map((p) => ({ loc: SITE_URL + '/' + p, lastmod: null }));
  items.forEach((a) => urls.push({ loc: SITE_URL + '/' + built[a.id], lastmod: isoDate(a.date) }));
  const sitemap =
    '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
    urls
      .map((u) => '  <url>\n    <loc>' + esc(u.loc) + '</loc>\n' + (u.lastmod ? '    <lastmod>' + u.lastmod + '</lastmod>\n' : '') + '  </url>')
      .join('\n') +
    '\n</urlset>\n';
  writeIfChanged(path.join(ROOT, 'sitemap.xml'), sitemap);

  // report
  console.log('Built ' + items.length + ' pages. Files: ' + stats.created + ' new, ' + stats.updated + ' updated, ' + stats.unchanged + ' unchanged, ' + stats.removed + ' removed.');
  items.forEach((a) => console.log('  ' + built[a.id]));
  if (warnings.length) {
    console.log('\nThings to look at:');
    warnings.forEach((w) => console.log('  - ' + w));
  }
}

try {
  main();
} catch (err) {
  console.error('\nBuild stopped: ' + err.message);
  process.exit(1);
}
